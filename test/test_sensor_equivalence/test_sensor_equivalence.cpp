// Behavior lock for the sensor extraction (layout step 5).
//
// Drives a fixed, seeded corpus of BLE advertisements and 802.11 frames
// through core's classification entry points - the exact calls the devices
// make - under every Recon selection value (0..20 and 255) and every Wi-Fi
// wants() mode, and compares every candidate produced against
// golden_894b508.txt. That file was generated by this same program compiled
// against commit 894b508, before the sensors were separated from core. Any
// change in which detector fires, its detail text, address, RSSI,
// confidence, or channel, or in the order candidates appear, fails the test.
//
//   ./tests_sensor_equivalence           compare against the golden file
//   ./tests_sensor_equivalence --emit    print the corpus output instead
//
// Run from test/ (the golden file path is relative to it).

#include <stdarg.h>
