"""Render the Hunter and Vixen heads for the T-Dongle-C5 status LCD.

Since 2026-11-01 the dongle no longer shows the owl (the owl is the Layers
and PRS logo): a Hunter shows the Hunter cat, and a Vixen shows the Vixen
fox. This script crops each head out of its logo master in assets/,
downsamples it to a 56 x 56 RGB565 bitmap on black, and writes both as
devices/lilygo-layerwand/src/C5LogoImages.cpp. Rerun it whenever a logo
master changes, then recheck the indicator boxes in C5LogoImages.h:

    python3 devices/lilygo-layerwand/tools/c5_logo_images.py

It prints where the green pixels of the Hunter head fall, row by row, which
is what the eye and cheek boxes are measured from. Requires Pillow.
"""

import pathlib
import struct

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[3]  # the repository root
OUTPUT = ROOT / "devices/lilygo-layerwand/src/C5LogoImages.cpp"

SIZE = 56   # pixels, square
PAD = 1     # pixels of black around the artwork

# (symbol, master, head crop box in the master's pixels: left, top, right, bottom)
HEADS = [
    ("kHunterImage", "assets/hunter-logo.png", (0, 0, 246, 237)),
    ("kVixenImage", "assets/vixen-logo.png", (14, 0, 178, 179)),
]


def head(master, box):
    image = Image.open(ROOT / master).convert("RGB").crop(box)
    side = max(image.size)
    square = Image.new("RGB", (side, side), (0, 0, 0))
    square.paste(image, ((side - image.width) // 2, (side - image.height) // 2))
    inner = square.resize((SIZE - 2 * PAD, SIZE - 2 * PAD), Image.LANCZOS)
    out = Image.new("RGB", (SIZE, SIZE), (0, 0, 0))
    out.paste(inner, (PAD, PAD))
    return out


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def is_green(p):
    # BringUpLogic's isGreenPixel, plus a floor so the black background never counts.
    return p[1] > p[0] and p[1] > p[2] and p[1] > 60


def array_body(image):
    pixels = image.load()
    words = [rgb565(*pixels[x, y]) for y in range(SIZE) for x in range(SIZE)]
    data = b"".join(struct.pack("<H", w) for w in words)  # LVGL native little-endian RGB565
    return "\n".join("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 24]) + "," for i in range(0, len(data), 24))


def main():
    parts = []
    for symbol, master, box in HEADS:
        image = head(master, box)
        name = symbol[1:].replace("Image", "").lower()
        parts.append(f"""const uint8_t k{name.capitalize()}Pixels[] = {{
{array_body(image)}
}};

}} // namespace

const lv_image_dsc_t {symbol} = {{
    {{LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_RGB565, 0, {SIZE}, {SIZE}, {SIZE * 2}, 0}},
    sizeof(k{name.capitalize()}Pixels),
    k{name.capitalize()}Pixels,
    nullptr,
    nullptr,
}};

namespace {{
""")
        if symbol == "kHunterImage":
            px = image.load()
            print("Hunter head green pixels (rows, columns), for kHunterEyeBox and kHunterCheekBox:")
            for y in range(SIZE):
                cols = [x for x in range(SIZE) if is_green(px[x, y])]
                if cols:
                    print(f"  row {y:2d}: columns {min(cols)}..{max(cols)}")
    body = "\n".join(parts)
    OUTPUT.write_text(f"""// LayerTime - passive early-warning firmware for the LILYGO T-Dongle-C5.
//
// Copyright (C) 2026 Michael Van Geertruy
//
// This program is free software: you can redistribute it and/or modify
// it under the terms of the GNU General Public License as published by
// the Free Software Foundation, either version 3 of the License, or
// (at your option) any later version.
//
// This program is distributed in the hope that it will be useful,
// but WITHOUT ANY WARRANTY; without even the implied warranty of
// MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
// GNU General Public License for more details.
//
// You should have received a copy of the GNU General Public License
// along with this program.  If not, see <https://www.gnu.org/licenses/>.

// GENERATED by devices/lilygo-layerwand/tools/c5_logo_images.py from
// assets/hunter-logo.png and assets/vixen-logo.png. Do not edit by hand;
// rerun the script when a logo changes. {SIZE} x {SIZE}, RGB565, LVGL native
// byte order, on a black background.

#if defined(LAYERTIME_TARGET_TDONGLE_C5)

#include "C5LogoImages.h"

namespace layertime {{
namespace tdongle_c5 {{

namespace {{

{body}
}} // namespace

}} // namespace tdongle_c5
}} // namespace layertime

#endif // LAYERTIME_TARGET_TDONGLE_C5
""", encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
